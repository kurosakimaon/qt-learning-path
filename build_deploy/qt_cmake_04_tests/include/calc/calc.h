// ============================================================================
// calc.h · 一个「值得被测试」的库：三个函数、三条边界、三种失败
// ----------------------------------------------------------------------------
// 为什么这三个函数值得写测试：
//   · clamp   —— 边界条件（lo == hi、value 正好等于边界）最容易写错
//   · mean    —— 空集合的返回值必须有个约定（这里用 NaN），否则调用方各猜各的
//   · percent —— 除零必须有个明确答案（这里约定 total <= 0 时返回 0）
// 三处约定都写在这里，测试就是它们的执法者。
//
// 注意：本头文件**不含任何 Widgets 头**，也不含 QObject。
// 所以它能被 cmdline 程序、被测试、被将来的服务端复用。
// ============================================================================

#pragma once

#include <QList>

namespace calc {

// 把 value 夹到 [lo, hi]。要求 lo <= hi，否则原样返回 value。
int clamp(int value, int lo, int hi);

// 算术平均。空集合返回 NaN（用 qIsNaN 判断，不要用 == 比较）。
double mean(const QList<double> &values);

// part 占 total 的百分比（0~100 的整数，向下取整）。
// total <= 0 时返回 0；结果被夹在 0~100（part > total 时封顶 100）。
int percent(int part, int total);

} // namespace calc
